// 뒤쪽 명사는 업무 동작 명사(HADA_NOUNS)로 한정하고, 길이가 긴 것부터 맞춘다
const ACTION_NOUNS = [...new Set([...HADA_NOUNS.filter(n => n !== '점검완료'), '작업'])].sort((a, b) => b.length - a.length);
// 보고서 이름처럼 한 덩어리로 굳은 말은 그대로 둔다
const COMPOUND_OK = new Set(['주간보고', '월간보고', '업무보고', '주간업무보고', '결과보고', '완료보고']);
// 동작 명사 바로 앞의 접두사는 동작 명사 쪽에 붙인다 (CBO미사용 → CBO 미사용, NAC재인증 → NAC 재인증)
const PREFIXES = ['미', '재', '불', '탈', '무'];
// 동작 명사 뒤에 붙어도 되는 것: 조사, '하다/되다' 활용, 접미사
const TAIL_OK = ['', '을', '를', '이', '가', '은', '는', '의', '에', '에서', '으로', '로', '도', '만', '과', '와', '까지', '부터', '에게', '처럼', '보다', '용', '별', '상', '건', '차', '중', '시', '후', '전'];
const tailOk = t => TAIL_OK.includes(t) || /^(하|되|됐|됨|된|했|함|할|한|해)/.test(t);

// 단어를 [앞말, 동작 명사…] 로 나눈다. 나눌 곳이 없으면 그대로 한 덩어리
function splitCompound(w) {
  if (COMPOUND_OK.has(w)) return [w];
  for (let i = 2; i < w.length; i++) {
    const rest = w.slice(i);
    const n = ACTION_NOUNS.find(x => rest.startsWith(x));
    if (!n) continue;
    const tail = rest.slice(n.length);
    // 뒤에 또 동작 명사가 이어지면 그 부분도 끝까지 깔끔히 나뉘어야 한다 ('압연작업진행실' 같은 이름은 그대로)
    if (!tailOk(tail) && !(ACTION_NOUNS.some(x => tail.startsWith(x)) && splitCompound(rest).length > 1)) continue;
    let head = w.slice(0, i), right = rest;
    if (head.length >= 3 && PREFIXES.includes(head[head.length - 1])) { right = head.slice(-1) + right; head = head.slice(0, -1); }
    if (!/[가-힣A-Za-z]/.test(head)) continue;
    return [...splitCompound(head), ...splitCompound(right)];
  }
  return [w];
}

