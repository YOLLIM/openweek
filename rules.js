function lineRules(line) {
  const out = [];
  const add = (original, suggestion, type, reason) => { if (original !== suggestion) out.push({ original, suggestion, type, reason }); };
  const lead = line.match(/^\s*(?:(?:\d+|[가-힣a-zA-Z])[.)]|[-*·•ㄴ└▶※]|\*)?\s*/)[0].length;  // 줄머리(번호·기호·들여쓰기)는 건드리지 않음
  const body = line.slice(lead);

  // 1) 단어 표기
  for (const [bad, good, type, reason, atStart] of WORDS) {
    const re = new RegExp(atStart ? `(?<![가-힣])${bad}[^\\s()\\[\\],.]*` : `[^\\s()\\[\\]]*${bad}[^\\s()\\[\\],.]*`, 'g');
    for (const m of body.matchAll(re)) add(m[0], m[0].replace(bad, good), type === '외래어' ? '맞춤법' : type, reason);
  }

  // 2) 안 되다 / 안 돼: '안되', '안돼', '않되' (부정의 '안'은 띄어 씀)
  for (const m of body.matchAll(/(^|\s)(않?)(되|돼|됨|됐|된)([가-힣]*)/g)) {
    if (m[2] === '않') add(`않${m[3]}${m[4]}`, `안 ${m[3]}${m[4]}`, '맞춤법', "부정은 '안 되다'로 씁니다('않되다'는 틀린 표기).");
  }
  for (const m of body.matchAll(/(^|\s)안(되|돼|됨|됐|된)([가-힣]*)/g)) {
    add(`안${m[2]}${m[3]}`, `안 ${m[2]}${m[3]}`, '띄어쓰기', "부정의 '안'은 뒷말과 띄어 씁니다.");
  }

  // 3) 명사 + 하다 띄어쓰기
  for (const m of body.matchAll(HADA_RE)) add(m[0], m[0].replace(/ +/, ''), '띄어쓰기', `'${m[1]}하다'는 한 단어이므로 붙여 씁니다.`);

  // 4) 의존명사 띄어쓰기: 할수/할때/할것/한것/하는것 (단 '-ㄹ수록'은 제외)
  for (const m of body.matchAll(/([가-힣]+)(수|때|것|줄|뿐|만큼)(?=[가-힣\s.,)]|$)/g)) {
    const w = m[1], last = w[w.length - 1], dep = m[2];
    const after = body.slice(m.index + m[0].length, m.index + m[0].length + 2);
    if (dep === '수' && after.startsWith('록')) continue;
    const j = jong(last);
    const ok = (j === 8 && ['수', '때', '것', '줄', '만큼'].includes(dep)) || (j === 4 && ['것', '줄', '만큼'].includes(dep)) || (last === '는' && ['것', '줄', '만큼'].includes(dep));
    if (!ok || w.length < 1) continue;
    if (dep === '수' && !/^\s*(있|없)/.test(body.slice(m.index + m[0].length))) continue;
    add(w + dep, `${w} ${dep}`, '띄어쓰기', `의존명사 '${dep}'은(는) 앞말과 띄어 씁니다.`);
  }

  // 4-2) 관형형 + 명사: 교체한후 → 교체한 후, 확인할예정 → 확인할 예정, 사용하는경우 → 사용하는 경우
  const ADN_RE = new RegExp(`([가-힣]+(?:${ADNOMINAL_ENDS.join('|')}))(${AFTER_ADNOMINAL.join('|')})(?=[\\s.,)]|$|에|의|을|를|이|으로|로|부터|까지|임|입니다)`, 'g');
  for (const m of body.matchAll(ADN_RE)) {
    if (m[1].length < 2 || /^불/.test(m[1]) && m[2] === '필요') continue;
    add(m[0], `${m[1]} ${m[2]}`, '띄어쓰기', `'${m[2]}'은(는) 앞말과 띄어 씁니다.`);
  }

  // 4-3) 명사 + 의존명사/명사: 점검중 → 점검 중, 확인시 → 확인 시, 교체후 → 교체 후, 보수관련 → 보수 관련
  const NA_RE = new RegExp(`(${HADA_NOUNS.join('|')})(${NOUN_AFTER.join('|')})(?=[\\s.,)]|$|에|의|을|를|이|인|임|으로|로|부터|까지|입니다)`, 'g');
  for (const m of body.matchAll(NA_RE)) add(m[0], `${m[1]} ${m[2]}`, '띄어쓰기', `'${m[2]}'은(는) 앞말과 띄어 씁니다.`);

  // 4-4) 조사 + 동사: 에대한 → 에 대한, 으로인해 → 으로 인해, 를위해 → 를 위해
  for (const [pt, verbs] of PARTICLE_VERBS) {
    const re = new RegExp(`([가-힣A-Za-z0-9)])${pt}(${verbs.join('|')})(?=[\\s.,)]|$|[가-힣])`, 'g');
    for (const m of body.matchAll(re)) if (!(pt === '로' && m[1] === '으')) add(`${m[1]}${pt}${m[2]}`, `${m[1]}${pt} ${m[2]}`, '띄어쓰기', `조사 '${pt}' 뒤의 '${m[2]}'는 띄어 씁니다.`);
  }

  // 4-5) 보조용언: 하지않음 → 하지 않음, 하고있음 → 하고 있음, 하게되어 → 하게 되어, 할 수있음 → 할 수 있음
  for (const m of body.matchAll(/([가-힣])지(않|못)([가-힣]*)/g)) add(m[0], `${m[1]}지 ${m[2]}${m[3]}`, '띄어쓰기', `'-지 ${m[2] === '않' ? '않다' : '못하다'}'는 띄어 씁니다.`);
  for (const m of body.matchAll(/([가-힣])고(있|계시)([가-힣]*)/g)) add(m[0], `${m[1]}고 ${m[2]}${m[3]}`, '띄어쓰기', "'-고 있다'는 띄어 씁니다.");
  for (const m of body.matchAll(/([가-힣])게(되|됨|됐|된)([가-힣]*)/g)) add(m[0], `${m[1]}게 ${m[2]}${m[3]}`, '띄어쓰기', "'-게 되다'는 띄어 씁니다.");
  for (const m of body.matchAll(/ 수(있|없)([가-힣]*)/g)) add(m[0].trim(), `수 ${m[1]}${m[2]}`, '띄어쓰기', "'수 있다/없다'는 띄어 씁니다.");

  // 4-6) 및·또는·때문·등: 앞뒤로 띄어 씀 (예: 장비및 → 장비 및, 고장때문에 → 고장 때문에, AP등 → AP 등)
  for (const m of body.matchAll(/([가-힣A-Za-z0-9)])(및|또는)/g)) add(m[0], `${m[1]} ${m[2]}`, '띄어쓰기', `'${m[2]}'은(는) 앞말과 띄어 씁니다.`);
  for (const m of body.matchAll(/(및|또는)([가-힣A-Za-z0-9(])/g)) {
    if (m[1] === '또는' || body[m.index - 1] === ' ' || m.index === 0) add(m[0], `${m[1]} ${m[2]}`, '띄어쓰기', `'${m[1]}' 뒤는 띄어 씁니다.`);
  }
  for (const m of body.matchAll(/([가-힣A-Za-z0-9)])때문/g)) add(m[0], `${m[1]} 때문`, '띄어쓰기', "의존명사 '때문'은 앞말과 띄어 씁니다.");
  for (const m of body.matchAll(/([A-Za-z0-9)])등(?=[\s.,)]|$|의|을|이|에|으로|도)/g)) add(m[0], `${m[1]} 등`, '띄어쓰기', "의존명사 '등'은 앞말과 띄어 씁니다.");

  // 4-9) 명사 + 명사: 스위치교체 → 스위치 교체, 장애처리 → 장애 처리 (단어별로 띄어 쓰는 것이 원칙)
  for (const m of body.matchAll(/[가-힣A-Za-z0-9]{3,}/g)) {
    const parts = splitCompound(m[0]);
    if (parts.length > 1) add(m[0], parts.join(' '), '띄어쓰기', `'${parts.slice(1).join("', '")}'은(는) 앞말과 띄어 씁니다. (단어별로 띄어 쓰는 것이 원칙이며, 전문 용어는 붙여 쓸 수도 있습니다)`);
  }

  // 4-7) 숫자 + 단위: 2 대 → 2대 (아라비아 숫자 뒤 단위는 붙여 씀)
  const UNIT_RE = new RegExp(`(\\d) (${UNITS.join('|')})(?=[\\s.,)]|$|의|을|를|이|가|에|씩|째|까지|부터|만)`, 'g');
  for (const m of body.matchAll(UNIT_RE)) add(m[0], `${m[1]}${m[2]}`, '띄어쓰기', '아라비아 숫자 뒤의 단위는 붙여 씁니다.');

  // 4-8) 괄호 안쪽 공백: ( 9/28 ) → (9/28)
  for (const m of body.matchAll(/\( +([^)]*?) *\)|\(([^)]*?[^ )]) +\)/g)) add(m[0], `(${(m[1] ?? m[2]).trim()})`, '띄어쓰기', '괄호 안쪽에는 띄어 쓰지 않습니다.');

  // 5) 같은 단어 두 번 연속 (예: 스위치 스위치)
  for (const m of body.matchAll(/(^|\s)([가-힣A-Za-z0-9]{2,}) +\2(?=\s|$|[.,)])/g)) {
    add(`${m[2]} ${m[2]}`, m[2], '오타', '같은 단어가 연속으로 두 번 들어갔습니다.');
  }

  // 6) 문장 중간의 겹친 공백
  for (const m of body.matchAll(/([^\s]) {2,}([^\s])/g)) add(m[0], `${m[1]} ${m[2]}`, '띄어쓰기', '공백이 두 칸 이상 들어갔습니다.');

  // 7) 문장부호: 쉼표·마침표 앞 공백, 겹친 쉼표, 한글 앞 쉼표 뒤 공백 누락
  for (const m of body.matchAll(/([가-힣A-Za-z0-9)]) +([,.])(?=\s|$)/g)) add(m[0], m[1] + m[2], '문장부호', '문장부호 앞에는 띄어 쓰지 않습니다.');
  for (const m of body.matchAll(/([가-힣A-Za-z0-9)]) +,([가-힣A-Za-z0-9(])/g)) add(m[0], `${m[1]}, ${m[2]}`, '문장부호', '쉼표는 앞말에 붙이고 뒤는 한 칸 띄어 씁니다.');
  for (const m of body.matchAll(/([^,]),,+([^,]|$)/g)) add(m[0], `${m[1]},${m[2]}`, '문장부호', '쉼표가 겹쳐 들어갔습니다.');
  for (const m of body.matchAll(/([가-힣A-Za-z)]),([가-힣])/g)) add(m[0], `${m[1]}, ${m[2]}`, '문장부호', '쉼표 뒤에는 한 칸 띄어 씁니다.');

  // 8) 단어 속에 끼어든 낱자음·모음 (예: 교체ㅁ 완료)
  for (const m of body.matchAll(/([가-힣])([ㄱ-ㅎㅏ-ㅣ]+)([가-힣]?)/g)) add(m[0], m[1] + m[3], '오타', '낱자음/모음이 잘못 입력된 것 같습니다.');

  // 줄머리 번호 뒤 공백 누락: 1.인천공장 → 1. 인천공장
  const nm = line.match(/^(\s*\d+[.)])([가-힣A-Za-z(])/);
  if (nm) add(nm[0].trimStart(), `${nm[1].trimStart()} ${nm[2]}`, '띄어쓰기', '번호 뒤에는 한 칸 띄어 씁니다.');

  // 9) 괄호 짝
  const open = (body.match(/\(/g) || []).length, close = (body.match(/\)/g) || []).length;
  if (open > close) {
    const m = body.match(/\([^)]*$/);
    if (m && m[0].length <= 40) add(m[0], m[0].replace(/\s*$/, ')'), '문장부호', '여는 괄호에 맞는 닫는 괄호가 없습니다.');
  }
  return out;
}

// entries: [{ id, text }] → [{ id, original, suggestion, type, reason }]
function ruleCheck(entries) {
  const issues = [];
  for (const e of entries) {
    const seen = new Set();
    for (const line of e.text.split('\n')) {
      for (const i of lineRules(line)) {
        if (seen.has(i.original) || !e.text.includes(i.original)) continue;
        seen.add(i.original);
        issues.push({ id: e.id, ...i });
      }
    }
  }
  return issues;
}

